/**
 * 由入口装配时调用；注册是幂等的，HMR 重复执行不会长出重复按钮。
 * 必须同步：异步注册会让首帧渲染时注册表还是空的，工具栏直接消失。
 */
export function installBuiltinTools(): void {
  registerTools(builtinTools);
}
